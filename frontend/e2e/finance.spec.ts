import { test, expect } from '@playwright/test'
import AxeBuilder from '@axe-core/playwright'
import { execFileSync } from 'node:child_process'
import { resolve } from 'node:path'
import type { CatalogOut } from '../src/api/schema.gen'

test('reader, account binding, imports, rules, administration and responsive accessibility', async ({ page }) => {
  await page.clock.setFixedTime(new Date('2026-10-07T12:00:00Z'))
  const pageErrors: string[] = []
  page.on('pageerror', error => pageErrors.push(error.message))
  expect((await page.request.get('/api/account')).status()).toBe(401)
  await page.goto('/')
  await expect(page.getByRole('heading', { name: 'Sign in', exact: true })).toBeVisible()
  const mainNavigation = page.getByRole('navigation', { name: 'Main navigation' })
  await expect(mainNavigation).toHaveCount(0)
  await expect(page.getByRole('link', { name: 'Analysis', exact: true })).toHaveCount(0)
  await expect(page.getByRole('link', { name: 'Statements', exact: true })).toHaveCount(0)
  await expect(mainNavigation.locator('a[href^="/admin"]')).toHaveCount(0)
  await page.goto('/admin')
  await page.getByLabel('Username', { exact: true }).fill(process.env.E2E_ADMIN_USERNAME || 'browser-test')
  await page.getByLabel('Password', { exact: true }).fill(process.env.E2E_ADMIN_PASSWORD || 'synthetic-browser-test-password')
  await page.getByRole('button', { name: 'Sign in to administration' }).click()
  await expect(page.getByRole('heading', { name: 'Import statement' })).toBeVisible()
  await expect(page.getByRole('navigation', { name: 'Administration navigation' }).getByRole('link')).toHaveCount(12)
  await expect(page.getByRole('navigation', { name: 'Administration navigation' }).getByRole('link', { name: 'Community labels', exact: true })).toHaveAttribute('href', '/admin/labels')
  await expect(mainNavigation).toHaveCount(0)
  await expect(mainNavigation.locator('a[href^="/admin"]')).toHaveCount(0)
  expect(await (await page.request.get('/api/account')).json()).toBeNull()
  await page.goto('/')
  await expect(page.getByRole('heading', { name: 'Community finances' })).toBeVisible()
  await expect(mainNavigation.getByRole('link')).toHaveCount(5)
  await expect(mainNavigation.getByRole('link', { name: 'Contacts', exact: true })).toHaveAttribute('href', '/contacts')
  await page.goto('/admin')
  const python = resolve('..', '.venv', process.platform === 'win32' ? 'Scripts' : 'bin', process.platform === 'win32' ? 'python.exe' : 'python')
  const buffer = execFileSync(python, ['-c', 'import sys; from tests.support import statement_pdf; sys.stdout.buffer.write(statement_pdf())'], { cwd: resolve('..') })
  const chooserPromise = page.waitForEvent('filechooser')
  await page.getByRole('button', { name: 'Select PDF' }).click()
  await (await chooserPromise).setFiles({ name: 'synthetic.pdf', mimeType: 'application/pdf', buffer })
  const review = page.getByRole('dialog', { name: 'Review import' })
  await expect(review).toBeVisible()
  await expect(review.getByRole('button', { name: 'Confirm detected account' })).toBeVisible()
  expect((await new AxeBuilder({ page }).analyze()).violations).toEqual([])
  await expect(page.getByRole('button', { name: 'Confirm and save the import' })).toHaveCount(0)
  await page.getByLabel('I confirm that this IBAN belongs to the community account.').check()
  await page.getByRole('button', { name: 'Confirm detected account' }).click()
  await page.getByRole('button', { name: 'Confirm and save the import' }).click()
  await expect(review).toHaveCount(0)
  await expect(page.getByRole('button', { name: 'Select PDF' })).toBeFocused()
  await expect(page.getByText('Import confirmed: 3 new transactions and 0 already recorded.')).toBeVisible()
  await expect(page.getByRole('heading', { name: 'Linked account' })).toBeVisible()
  await page.getByRole('link', { name: 'Rules', exact: true }).click()
  await page.getByLabel('Name', { exact: true }).fill('Cleaning rule')
  await page.getByLabel('Description', { exact: true }).fill('cleaning')
  await page.getByLabel('Set category').selectOption({ label: 'Cleaning' })
  await page.getByRole('button', { name: 'Preview on history' }).click()
  await expect(page.getByText('Matches 1 transaction.', { exact: false })).toBeVisible()
  await page.getByRole('button', { name: 'Confirm and apply to 1 transaction' }).click()
  await expect(page.getByText('Rule applied to the history.', { exact: true })).toBeVisible()
  await page.getByRole('link', { name: 'Classify transactions' }).click()
  await expect(page.getByText('Cleaning receipt', { exact: true })).toBeVisible()
  await page.getByRole('button', { name: /View transaction.*Cleaning receipt/ }).click()
  await expect(page.getByRole('dialog')).toBeVisible()
  await expect(page.getByRole('dialog').getByRole('combobox', { name: 'Category', exact: true })).toHaveValue('5')
  await page.getByRole('dialog').getByRole('textbox', { name: 'Merchant', exact: true }).fill('Synthetic cleaning company')
  const detail = page.getByRole('dialog', { name: 'Transaction details' })
  const tagInput = detail.getByRole('combobox', { name: 'Tags', exact: true })
  const tagsBefore: CatalogOut[] = await (await page.request.get('/api/catalog/tags')).json()
  await tagInput.click()
  await expect(detail.getByRole('listbox').getByRole('option')).toHaveText(tagsBefore.slice(0, 8).map(tag => tag.name))
  await tagInput.fill('f')
  await expect(detail.getByLabel('Tag preview')).toHaveCSS('background-color', 'rgb(198, 193, 2)')
  await tagInput.fill('fa')
  await expect(detail.getByLabel('Tag preview')).toHaveCSS('background-color', 'rgb(215, 112, 137)')
  await tagInput.fill('fam')
  await expect(detail.getByLabel('Tag preview')).toHaveCSS('background-color', 'rgb(43, 204, 180)')
  await tagInput.press('Enter')
  await tagInput.fill(tagsBefore[0].name)
  await detail.getByRole('option', { name: tagsBefore[0].name, exact: true }).click()
  expect(await (await page.request.get('/api/catalog/tags')).json()).toEqual(tagsBefore)
  expect((await new AxeBuilder({ page }).analyze()).violations).toEqual([])
  await page.screenshot({ path: 'test-results/financial-tag-picker-desktop.png', fullPage: true })
  const viewport = page.viewportSize()
  await page.setViewportSize({ width: 390, height: 844 })
  await tagInput.click()
  const options = detail.getByRole('listbox')
  await expect(options).toBeVisible()
  const bounds = await options.boundingBox()
  expect(bounds).not.toBeNull()
  expect(bounds!.x).toBeGreaterThanOrEqual(0)
  expect(bounds!.x + bounds!.width).toBeLessThanOrEqual(390)
  expect(await detail.evaluate(element => element.scrollWidth <= element.clientWidth)).toBe(true)
  expect((await new AxeBuilder({ page }).analyze()).violations).toEqual([])
  await page.screenshot({ path: 'test-results/financial-tag-picker-mobile.png', fullPage: true })
  if (viewport) await page.setViewportSize(viewport)
  await page.getByRole('button', { name: 'Save classification' }).click()
  await expect(page.getByRole('dialog')).toHaveCount(0)
  await page.reload()
  await expect(page.getByRole('row').filter({ hasText: 'Cleaning receipt' }).getByText('fam', { exact: true })).toHaveCSS('background-color', 'rgb(43, 204, 180)')
  const savedTags: CatalogOut[] = await (await page.request.get('/api/catalog/tags')).json()
  expect(savedTags).toHaveLength(tagsBefore.length + 1)
  expect(savedTags.find(tag => tag.name === 'fam')?.color).toBe('#2bccb4')
  await page.goto('/')
  await page.getByRole('combobox', { name: 'Category', exact: true }).selectOption({ label: 'Cleaning' })
  await page.getByRole('link', { name: 'View transactions in category Cleaning', exact: true }).click()
  await expect(page).toHaveURL(/category=5/)
  await expect(page).toHaveURL(/flow=expense/)
  await expect(page.getByRole('heading', { name: '1 transaction', exact: true })).toBeVisible()
  await page.goto('/admin')
  await page.getByRole('link', { name: 'General', exact: true }).click()
  await page.getByLabel('Community name', { exact: true }).fill('Parkside Community')
  await page.getByRole('button', { name: 'Save changes', exact: true }).click()
  await expect(page.getByText('Community name updated.', { exact: true })).toBeVisible()
  await expect(page).toHaveTitle('Parkside Community')
  await expect(page.locator('header.topbar')).toContainText('Parkside Community')
  await page.screenshot({ path: 'test-results/admin-general-desktop.png', fullPage: true })
  await expect(page.locator('meta[name="apple-mobile-web-app-title"]')).toHaveAttribute('content', 'Parkside Community')
  const manifest = await (await page.request.get('/manifest.webmanifest')).json()
  expect(manifest.name).toBe('Parkside Community')
  expect(manifest.display).toBe('standalone')
  for (const icon of manifest.icons) expect((await page.request.get(icon.src)).ok()).toBe(true)
  expect((await page.request.get('/icons/apple-touch-icon.png')).ok()).toBe(true)
  expect((await page.request.get('/analytics')).status()).toBe(404)
  expect((await page.request.get('/statements')).status()).toBe(404)
  await expect(page.locator('.sidebar-foot')).toHaveCount(0)
  await expect(page.locator('header.topbar')).not.toContainText('Dark mode')
  for (const route of ['/', '/transactions', '/admin/catalog', '/admin/statements', '/admin/general', '/admin/storage']) {
    await page.goto(route)
    await expect(page.locator('main h1')).toBeVisible()
    await page.waitForLoadState('networkidle')
    expect((await new AxeBuilder({ page }).analyze()).violations).toEqual([])
  }
  await page.goto('/')
  await page.waitForLoadState('networkidle')
  await expect(page.getByRole('button', { name: 'Hide amounts', exact: true })).toHaveAttribute('aria-pressed', 'false')
  await expect(page.locator('.kpi .sensitive-value').first()).toHaveCSS('filter', 'none')
  await page.screenshot({ path: 'test-results/finance-desktop.png', fullPage: true })
  await page.getByRole('button', { name: 'Hide amounts', exact: true }).click()
  await expect(page.locator('.kpi .sensitive-value').first()).toHaveCSS('filter', 'blur(6px)')
  await expect(page.locator('.recharts-yAxis-tick-labels .recharts-cartesian-axis-tick-value').first()).toHaveCSS('filter', 'blur(6px)')
  await expect(page.locator('.category-share .sensitive-value').first()).toHaveCSS('filter', 'blur(6px)')
  expect((await new AxeBuilder({ page }).analyze()).violations).toEqual([])
  await page.screenshot({ path: 'test-results/finance-private.png', fullPage: true })
  await page.reload()
  await expect(page.getByRole('button', { name: 'Show amounts', exact: true })).toHaveAttribute('aria-pressed', 'true')
  await page.goto('/transactions')
  await page.getByRole('button', { name: /View transaction.*Cleaning receipt/ }).click()
  await expect(page.getByRole('dialog').locator('.sensitive-value').first()).toHaveCSS('filter', 'blur(6px)')
  await page.getByRole('button', { name: 'Close', exact: true }).click()
  await page.goto('/admin/transactions')
  await expect(page.locator('tbody .sensitive-value').first()).toHaveCSS('filter', 'none')
  await expect(page.getByRole('button', { name: /^(Show|Hide) amounts$/ })).toHaveCount(0)
  await page.goto('/')
  await page.getByRole('button', { name: 'Show amounts', exact: true }).click()
  await expect(page.locator('.kpi .sensitive-value').first()).toHaveCSS('filter', 'none')
  await page.getByRole('button', { name: 'Dark mode' }).click()
  expect((await new AxeBuilder({ page }).analyze()).violations).toEqual([])
  await page.screenshot({ path: 'test-results/finance-dark.png', fullPage: true })
  await page.getByRole('button', { name: 'Light mode' }).click()
  await page.setViewportSize({ width: 390, height: 844 })
  await page.reload()
  await page.waitForLoadState('networkidle')
  await expect(mainNavigation).toBeHidden()
  await page.getByRole('button', { name: 'Navigation menu', exact: true }).click()
  await expect(mainNavigation.getByRole('link')).toHaveCount(5)
  await expect(mainNavigation.locator('a[href^="/admin"]')).toHaveCount(0)
  await page.getByRole('button', { name: 'Navigation menu', exact: true }).click()
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
  expect((await new AxeBuilder({ page }).analyze()).violations).toEqual([])
  await page.screenshot({ path: 'test-results/finance-mobile.png', fullPage: true })
  await page.goto('/admin/general')
  await expect(page.getByRole('heading', { name: 'General', exact: true, level: 1 })).toBeVisible()
  await page.getByRole('button', { name: 'Navigation menu', exact: true }).click()
  await expect(page.getByRole('navigation', { name: 'Administration navigation' }).getByRole('link')).toHaveCount(12)
  await page.getByRole('button', { name: 'Navigation menu', exact: true }).click()
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
  expect((await new AxeBuilder({ page }).analyze()).violations).toEqual([])
  await page.screenshot({ path: 'test-results/admin-general-mobile.png', fullPage: true })
  await page.getByRole('button', { name: 'User menu', exact: true }).click()
  await page.getByRole('button', { name: 'Sign out' }).click()
  await page.goto('/transactions')
  await expect(page.getByRole('heading', { name: 'Sign in', exact: true })).toBeVisible()
  await expect(page.getByText('Cleaning receipt', { exact: true })).toHaveCount(0)
  await expect(mainNavigation.locator('a[href^="/admin"]')).toHaveCount(0)
  await page.goto('/admin')
  await expect(page.getByRole('button', { name: 'Sign in to administration' })).toBeVisible()
  expect((await page.request.get('/api/admin/statements')).status()).toBe(401)
  expect(pageErrors).toEqual([])
})
