import { test, expect } from '@playwright/test'
import AxeBuilder from '@axe-core/playwright'

test.afterEach(async ({ page }) => {
  if (process.env.E2E_BASE_URL || page.url() === 'about:blank') return
  const headers = { Origin: new URL(page.url()).origin, 'X-Juntia-Request': '1' }
  expect((await page.request.patch('/api/admin/settings/features/coefficient', { headers, data: { enabled: true } })).status()).toBe(200)
  expect((await page.request.post('/api/admin/test-reset-login-attempts', { headers })).status()).toBe(204)
})

test('disabled coefficient feature removes every control and requirement', async ({ page, browser }) => {
  test.skip(Boolean(process.env.E2E_BASE_URL), 'Requires the disposable synthetic application')
  test.setTimeout(120_000)
  await page.goto('/admin/features')
  await page.getByLabel('Username', { exact: true }).fill('browser-test')
  await page.getByLabel('Password', { exact: true }).fill('synthetic-browser-test-password')
  await page.getByRole('button', { name: 'Sign in to administration' }).click()
  const toggle = page.getByRole('switch', { name: 'Ownership coefficients' })
  await expect(toggle).toHaveAttribute('aria-checked', 'true')
  await toggle.click()
  await expect(toggle).toHaveAttribute('aria-checked', 'false')
  expect(await (await page.request.get('/api/features')).json()).toEqual({ coefficient: false, google_login: false, actions: true, events: false })
  await page.getByRole('link', { name: 'Dwellings', exact: true }).click()
  await expect(page.getByRole('heading', { name: 'Dwellings', exact: true })).toBeVisible()
  await page.getByRole('button', { name: 'Create dwelling', exact: true }).click()
  const create = page.getByRole('dialog', { name: 'Create dwelling', exact: true })
  await expect(create.getByLabel('Ownership coefficient (%)', { exact: true })).toHaveCount(0)
  await expect(create).not.toContainText(/coefficient/i)
  await create.getByLabel('Dwelling name', { exact: true }).fill('Flag disabled 1 A')
  const creating = page.waitForRequest(request => request.method() === 'POST' && request.url().endsWith('/api/admin/dwellings'))
  await create.getByRole('button', { name: 'Save dwelling', exact: true }).click()
  expect((await creating).postDataJSON()).toEqual({ label: 'Flag disabled 1 A' })
  await expect(create).toHaveCount(0)
  await expect(page.getByRole('columnheader', { name: 'Ownership coefficient', exact: true })).toHaveCount(0)
  await page.getByRole('button', { name: 'Edit dwelling Flag disabled 1 A', exact: true }).click()
  const edit = page.getByRole('dialog', { name: 'Edit dwelling', exact: true })
  await expect(edit).not.toContainText(/coefficient/i)
  await edit.getByLabel('Dwelling name', { exact: true }).fill('Flag updated 1 A')
  const editing = page.waitForRequest(request => request.method() === 'PATCH' && request.url().includes('/api/admin/dwellings/'))
  await edit.getByRole('button', { name: 'Save dwelling', exact: true }).click()
  expect((await editing).postDataJSON()).not.toHaveProperty('coefficient')
  await expect(edit).toHaveCount(0)
  const dwellings = await (await page.request.get('/api/admin/dwellings')).json()
  expect(dwellings[0].coefficient).toBeNull()
  await page.getByRole('link', { name: 'Users', exact: true }).click()
  await page.getByRole('button', { name: 'Invite user', exact: true }).click()
  const invitation = page.getByRole('dialog', { name: 'Invite user', exact: true })
  const email = 'flag-off@example.org'
  await invitation.getByLabel('Name', { exact: true }).fill('Feature flag resident')
  await invitation.getByLabel('Email', { exact: true }).fill(email)
  await invitation.getByRole('combobox', { name: 'Dwelling', exact: true }).selectOption({ label: 'Flag updated 1 A' })
  await expect(invitation).not.toContainText(/coefficient/i)
  await invitation.getByRole('button', { name: 'Send invitation', exact: true }).click()
  await expect(invitation).toHaveCount(0)
  await expect(page.getByRole('table')).not.toContainText('%')
  const users = await (await page.request.get('/api/admin/users')).json()
  expect(users[0].coefficient).toBeNull()
  await page.getByRole('button', { name: `Edit user ${email}`, exact: true }).click()
  await expect(page.getByRole('dialog', { name: 'Edit user', exact: true })).not.toContainText(/coefficient/i)
  await page.getByRole('button', { name: 'Cancel', exact: true }).click()
  const messages: { to: string; body: string }[] = await (await page.request.get('/api/admin/test-mailbox')).json()
  const link = messages.find(message => message.to === email)?.body.match(/https?:\/\/[^\s]+/)?.[0]
  if (!link) throw new Error('Synthetic invitation link was not captured')
  const context = await browser.newContext({ baseURL: new URL(page.url()).origin })
  try {
    const resident = await context.newPage()
    await resident.goto(link)
    const password = 'synthetic feature flag password'
    await resident.getByLabel('New password', { exact: true }).fill(password)
    await resident.getByLabel('Repeat password', { exact: true }).fill(password)
    await resident.getByRole('button', { name: 'Save password', exact: true }).click()
    await expect(resident.getByRole('heading', { name: 'Password saved', exact: true })).toBeVisible()
    await resident.getByRole('link', { name: 'Back to sign in', exact: true }).click()
    await resident.getByLabel('Email', { exact: true }).fill(email)
    await resident.getByLabel('Password', { exact: true }).fill(password)
    await resident.getByRole('button', { name: 'Sign in', exact: true }).click()
    await expect(resident.getByRole('heading', { name: 'Community finances', exact: true })).toBeVisible()
    await resident.getByRole('button', { name: 'User menu', exact: true }).click()
    await resident.getByRole('link', { name: /My profile/ }).click()
    await expect(resident.getByLabel('Name', { exact: true })).toHaveValue('Feature flag resident')
    await expect(resident.locator('main')).not.toContainText(/coefficient/i)
    expect((await (await resident.request.get('/api/auth/profile')).json()).coefficient).toBeNull()
    expect((await new AxeBuilder({ page: resident }).analyze()).violations).toEqual([])
    await resident.screenshot({ path: 'test-results/profile-without-coefficient.png', fullPage: true })
  } finally {
    await context.close()
  }
})
