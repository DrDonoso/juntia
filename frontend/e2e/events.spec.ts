test('a saved all-day event can switch to timed mode without losing its draft', async ({ page }) => {
  test.skip(Boolean(process.env.E2E_BASE_URL), 'Requires a disposable synthetic application')
  await adminLogin(page)
  await enableEvents(page)
  const headers = { Origin: new URL(page.url()).origin, 'X-Juntia-Request': '1' }
  const created = await page.request.post('/api/events', { headers, data: {
    title: 'Convertible all-day event', timezone: 'Europe/Madrid', all_day: true,
    starts_on: '2037-05-10', ends_on: '2037-05-12',
  } })
  expect(created.status()).toBe(201)
  const event = await created.json()
  await page.goto(`/events/${event.id}`)
  await expect(page).toHaveURL(new RegExp(`/events\\?event=${event.id}$`))
  await page.locator('dialog.event-detail-modal').getByRole('button', { name: 'Edit event', exact: true }).click()
  const editor = page.getByRole('dialog', { name: 'Edit event', exact: true })
  await editor.getByLabel('Title', { exact: true }).fill('Draft kept when changing the schedule')
  const allDay = editor.getByLabel('All day', { exact: true })
  await allDay.uncheck()
  await expect(editor.getByRole('group', { name: 'Start', exact: true })).toBeVisible()
  await expect(editor.getByRole('group', { name: 'Start', exact: true })).toContainText('10/05/2037')
  await expect(editor.getByRole('group', { name: 'End', exact: true })).toContainText('11/05/2037')
  await expect(editor.locator('[data-type="hour"][data-placeholder="true"]')).toHaveCount(2)
  await expect(editor.locator('[data-type="minute"][data-placeholder="true"]')).toHaveCount(2)
  await expect(page.getByText('This page could not be displayed')).toHaveCount(0)
  await expect(editor.getByLabel('Title', { exact: true })).toHaveValue('Draft kept when changing the schedule')
  await editor.getByRole('button', { name: 'Save event' }).click()
  await expect(editor).toBeVisible()
  expect(await (await page.request.get(`/api/events/${event.id}`)).json()).toMatchObject({ version: 1, all_day: true })
  await allDay.check()
  await expect(editor.getByRole('group', { name: 'First day', exact: true })).toHaveText('10/05/2037')
  await expect(editor.getByRole('group', { name: 'Last day (inclusive)', exact: true })).toHaveText('11/05/2037')
  await allDay.uncheck()
  await fillEventTime(editor, 'starts_at', '09:15')
  await fillEventTime(editor, 'ends_at', '17:45')
  await editor.getByRole('button', { name: 'Save event' }).click()
  await expect(editor).not.toBeVisible()
  const saved = await (await page.request.get(`/api/events/${event.id}`)).json()
  expect(saved).toMatchObject({
    id: event.id, version: 2, all_day: false, starts_on: null, ends_on: null,
    starts_at: '2037-05-10T07:15:00Z', ends_at: '2037-05-11T15:45:00Z',
    title: 'Draft kept when changing the schedule',
  })
})

for (const height of [900, 1200]) test(`the desktop calendar uses the space above without scrolling its event dialog (${height}px)`, async ({ page }) => {
  test.skip(Boolean(process.env.E2E_BASE_URL), 'Requires a disposable synthetic application')
  await page.setViewportSize({ width: 1280, height })
  await adminLogin(page)
  await enableEvents(page)
  await page.goto('/events')
  await page.getByRole('button', { name: 'New event', exact: true }).click()
  const editor = page.getByRole('dialog', { name: 'New event', exact: true })
  const input = editor.getByRole('group', { name: 'End', exact: true })
  const trigger = input.getByRole('button', { name: 'Open calendar for End', exact: true })
  await trigger.scrollIntoViewIfNeeded()
  const before = await editor.evaluate(element => ({ top: element.scrollTop, height: element.scrollHeight }))
  const inputTop = await input.evaluate(element => element.getBoundingClientRect().top)
  await trigger.click()
  const popup = page.locator('.event-calendar-popover')
  await expect(popup).toBeVisible()
  await expect(popup).toHaveAttribute('data-placement', 'top')
  expect(await popup.evaluate(element => element.getBoundingClientRect().bottom)).toBeLessThanOrEqual(inputTop)
  const bounds = await editor.boundingBox()
  expect(await popup.evaluate(element => element.getBoundingClientRect().top)).toBeGreaterThanOrEqual(bounds!.y)
  expect(await editor.evaluate(element => element.scrollTop)).toBe(before.top)
  expect(await editor.evaluate(element => element.scrollHeight)).toBe(before.height)
  const popupSize = await popup.evaluate(element => ({
    scrollHeight: element.scrollHeight, clientHeight: element.clientHeight,
    maxHeight: getComputedStyle(element).maxHeight, box: element.getBoundingClientRect().toJSON(),
  }))
  expect(popupSize.scrollHeight, JSON.stringify({ ...popupSize, dialog: bounds, inputTop, before })).toBeLessThanOrEqual(popupSize.clientHeight)
  await page.keyboard.press('Escape')
  await expect(editor).toBeVisible()
})

