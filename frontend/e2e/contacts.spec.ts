const password = 'synthetic contact resident password'

async function contactAction(page: Page, action: 'Edit' | 'History' | 'Delete') {
  await page.getByRole('button', { name: 'Actions for Community lift', exact: true }).click()
  await page.getByRole('menu', { name: 'Actions for Community lift' }).getByRole('menuitem', { name: action, exact: true }).click()
}

async function resident(context: BrowserContext, admin: Page, email: string, name: string, dwellingId: number) {
  const origin = new URL(admin.url()).origin
  const headers = { Origin: origin, 'X-Juntia-Request': '1' }
  const response = await admin.request.post('/api/admin/users', {
    headers, data: { name, email, dwelling_id: dwellingId },
  })
  expect(response.status()).toBe(201)
  const messages: { to: string; body: string }[] = await (await admin.request.get('/api/admin/test-mailbox')).json()
  const message = [...messages].reverse().find(item => item.to === email)
  const match = message?.body.match(/\/activate#token=([a-f0-9]{64})/)
  if (!match) throw new Error('Synthetic invitation token was not delivered')
  const page = await context.newPage()
  page.setDefaultTimeout(10000)
  expect((await page.request.post('/api/auth/activate', {
    headers, data: { token: match[1], password },
  })).status()).toBe(204)
  await page.goto('/contacts?q=lift')
  await expect(page.getByRole('heading', { name: 'Sign in', exact: true })).toBeVisible()
  await page.getByLabel('Email', { exact: true }).fill(email)
  await page.getByLabel('Password', { exact: true }).fill(password)
  await page.getByRole('button', { name: 'Sign in', exact: true }).click()
  await expect(page).toHaveURL(/\/contacts\?q=lift$/)
  return page
}

